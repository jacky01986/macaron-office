function full() {
  return [CORE, SERVICE, FAQ, FLAVOR_PC, FLAVOR_603, CLASSIC].join('\n\n');
}

function section(name) {
  const map = { core: CORE, faq: FAQ, pc: FLAVOR_PC, f603: FLAVOR_603, service: SERVICE, classic: CLASSIC };
  return map[String(name || '').toLowerCase()] || '';
}

function register(app) {
  app.get('/api/brand-kb', function (req, res) {
    const s = req.query && req.query.section;
    const text = s ? section(s) : full();
    res.json({ ok: true, section: s || 'full', chars: text.length, text: text });
  });
}

